#!/usr/bin/env python3
"""Inventory a git repository and partition it into review slices for a security audit.

Lists every tracked file (and, with ``--include-untracked``, every untracked file git
does not ignore), classifies each one, counts its lines, and packs the reviewable
classes into slices small enough for one reviewer to read in full. Writes the result as
a JSON ledger and prints a short summary.

Classes:

- ``code``: application source and configuration, read line by line.
- ``test``: test code, read in larger slices with a lighter checklist.
- ``prose``: documentation and plain text, read for secrets, personal data, and insecure
  operating instructions.
- ``lock``: dependency lock files, assigned to the supply-chain pass, not sliced.
- ``vendored``: third-party or generated files, assigned to the supply-chain pass.
- ``binary``: non-text files, listed so the configuration pass can check their names
  and provenance.

Every file appears in the ledger exactly once with its class and, for sliced classes,
its slice id. Uses only the standard library.
"""

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path, PurePosixPath

DEFAULT_BUDGET = 5000
TEST_BUDGET_FACTOR = 2
PROSE_BUDGET_FACTOR = 4
SNIFF_BYTES = 8192
GIT = shutil.which("git")

